local function loadGenerated(mod, path)
    local source, readErr = mod:read(path)
    if not source then
        error(("KEP Port: couldn't read %s: %s"):format(path, tostring(readErr)), 0)
    end

    local chunk, loadErr = loadstring(source, path)
    if not chunk then
        error(("KEP Port: syntax error in %s: %s"):format(path, tostring(loadErr)), 0)
    end

    local register = chunk()
    if type(register) ~= "function" then
        error(("KEP Port: %s must return function(mod)"):format(path), 0)
    end
    register(mod)
end

